import {build} from 'esbuild';
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const root = new URL('../', import.meta.url);
const output = new URL('functions/vault-account-runtime.js', root);
const result = await build({absWorkingDir: fileURLToPath(root),
    entryPoints: [fileURLToPath(new URL('functions/vault-account-entry.mjs', root))], bundle: true, write: false,
    tsconfigRaw: {}, pure: ['Object.freeze'],
    platform: 'node', target: 'node22', format: 'cjs', legalComments: 'none',
    banner: {js: '// Generated by scripts/build-vault-account-backend.mjs; edit the source modules.\n/* global URL */'}});
const bytes = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
    const current = await readFile(output);
    if (!current.equals(Buffer.from(bytes))) throw new Error('Vault Account backend bundle is stale');
    console.log('Vault Account backend bundle verified');
} else {
    await writeFile(output, bytes);
    console.log('Vault Account backend bundle built');
}
